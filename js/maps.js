const width = window.innerWidth;
const DEFAULT_ZOOM = width < 768 ? 3 : 4;
const DEFAULT_CENTER = [55.54195423596562, 76.195574];
// Метки по макету: обычная, при наведении и выбранная (открыта карточка организации)
const PIN_ICONS = {
  default: 'icons/pin.svg',
  hover: 'icons/pin-hover.svg',
  active: 'icons/pin-active.svg',
};

// Заранее загружаем иконки состояний, чтобы при наведении не было мигания
Object.values(PIN_ICONS).forEach((src) => { new Image().src = src; });

document.addEventListener('DOMContentLoaded', () => {
  ymaps.ready(init);
});

function init() {
  const CLUSTER_SIZE = 56;
  const customClusterLayout = ymaps.templateLayoutFactory.createClass(
    '<div class="map-cluster">$[properties.geoObjects.length]</div>'
  );

  const clusterer = new ymaps.Clusterer({
    clusterIconLayout: customClusterLayout,

    /*
      Область клика — весь круг. Координаты считаются от точки привязки группы,
      а своя разметка значка рисуется от этой точки вправо-вниз (clusterIconOffset
      для своей разметки не работает). Поэтому значок центрируется стилями
      (.map-cluster: left/top -28px), а круг клика стоит в точке [0, 0].
    */
    clusterIconShape: {
      type: 'Circle',
      coordinates: [0, 0],
      radius: CLUSTER_SIZE / 2
    },

    groupByCoordinates: false,
    clusterDisableClickZoom: true,
    clusterHideIconOnBalloonOpen: false,
    geoObjectHideIconOnBalloonOpen: false
  });

  const map = new ymaps.Map("map", {
    center: DEFAULT_CENTER,
    zoom: DEFAULT_ZOOM,
  },
    clusterer,
  );

  // Кнопки масштаба: оформление в css/sections.css (.map-zoom), позиции — по макету
  const zoomLayout = (mod, title, sign) => ymaps.templateLayoutFactory.createClass(
    `<button type="button" class="map-zoom map-zoom--${mod}" title="${title}" aria-label="${title}">${sign}</button>`
  );

  const zoomInBtn = new ymaps.control.Button({
    data: { content: '' },
    options: { layout: zoomLayout('in', 'Приблизить', '+') }
  });

  const zoomOutBtn = new ymaps.control.Button({
    data: { content: '' },
    options: { layout: zoomLayout('out', 'Отдалить', '−') }
  });

  // Десктоп: 44×44, справа 20, сверху 184, промежуток 14. Мобильный: 32×32, справа 16, сверху 320, промежуток 4
  const zoomMobile = window.matchMedia('(max-width: 767px)');
  const placeZoom = () => {
    const [right, top, step] = zoomMobile.matches ? [16, 320, 36] : [20, 184, 58];
    zoomInBtn.options.set('position', { right, top });
    zoomOutBtn.options.set('position', { right, top: top + step });
  };
  placeZoom();
  zoomMobile.addEventListener('change', placeZoom);

  zoomInBtn.events.add('click', () => {
    map.setZoom(map.getZoom() + 1, { checkZoomRange: true });
  });

  zoomOutBtn.events.add('click', () => {
    map.setZoom(map.getZoom() - 1, { checkZoomRange: true });
  });

  new SlimSelect({
    select: '#cities',
    settings: {
      showSearch: false,
      contentPosition: 'absolute',
      modal: 'off',
      searchPlaceholder: 'Выберите город',
    },
    events: {
      afterChange: (newVal) => {
        const current = points.find(item => item.marker === newVal[0].value)
        if (current) {
          map.setCenter(current.coordinates, 14);
        } else {
          map.setCenter(window.__mapDefaultCenter, window.__mapDefaultZoom);
        }
      }
    },
  });

  // Показываем выбор города только после замены обычного select на SlimSelect
  document.querySelector('#cities').closest('.select').classList.add('is-ready');

  let minLon, maxLon, minLat, maxLat, initIter = true

  // ДОБАВЛЕНИЕ ГЕО МЕТОК
  let markers = [];

  // Карточка организации — ссылка на её страницу (разметка в index.html)
  const card = document.querySelector('.js-map-card');
  const cardImage = card.querySelector('.map-card__image');
  const cardName = card.querySelector('.map-card__name');

  // Выбранная метка — та, чья карточка сейчас открыта
  let activeMarker = null;

  const setActiveMarker = (marker) => {
    if (activeMarker) activeMarker.options.set('iconImageHref', PIN_ICONS.default);
    activeMarker = marker;
    if (activeMarker) activeMarker.options.set('iconImageHref', PIN_ICONS.active);
  };

  const showCard = (item, marker) => {
    setActiveMarker(marker);
    card.href = item.url;
    cardImage.src = item.image;
    cardName.textContent = item.name;
    card.setAttribute('aria-label', `${item.name} — открыть страницу организации`);
    card.hidden = false;
  };

  const hideCard = () => {
    card.hidden = true;
    setActiveMarker(null);
  };

  // Прячем карточку, когда карту двигают, масштабируют или кликают мимо метки
  map.events.add(['zoomchange', 'actionbegin', 'click'], hideCard);

  points.forEach(item => {

    const marker = new ymaps.Placemark(
      item.coordinates, {}, {
      iconLayout: 'default#image',
      iconImageHref: PIN_ICONS.default,
      iconImageSize: [32, 32],
      iconImageOffset: [-16, -31], // кончик метки — точно в координате
      hasBalloon: false,
    });

    // Наведение подсвечивает метку, но не трогает выбранную
    marker.events
      .add('mouseenter', () => {
        if (marker !== activeMarker) marker.options.set('iconImageHref', PIN_ICONS.hover);
      })
      .add('mouseleave', () => {
        if (marker !== activeMarker) marker.options.set('iconImageHref', PIN_ICONS.default);
      });

    const [one, two] = item.coordinates;

    if (initIter) {
      initIter = false;
      minLon = maxLon = two;
      minLat = maxLat = one;
    }
    if (minLon > two) minLon = two;
    if (maxLon < two) maxLon = two;
    if (minLat > one) minLat = one;
    if (maxLat < one) maxLat = one;

    marker.events.add('click', () => {
      setTimeout(() => {
        showCard(item, marker)
      }, 0);
    });

    markers.push(marker)
  })

  //ДОБАВЛЕНИЕ ГЕО МЕТОК и настройка внешного вида карты
  if (map) {
    const centerLat = (minLat + maxLat) / 2;
    const centerLon = (minLon + maxLon) / 2;

    map.setCenter([centerLat, centerLon], DEFAULT_ZOOM);

    window.__mapDefaultCenter = [centerLat, centerLon];
    window.__mapDefaultZoom = DEFAULT_ZOOM;

    map.controls.remove("geolocationControl"); // удаляем геолокацию
    map.controls.remove("searchControl"); // удаляем поиск
    map.controls.remove("trafficControl"); // удаляем контроль трафика
    map.controls.remove("typeSelector"); // удаляем тип
    map.controls.remove("fullscreenControl"); // удаляем кнопку перехода в полноэкранный режим
    map.controls.remove("rulerControl"); // удаляем контрол правил
    map.behaviors.disable('scrollZoom');
    map.controls.remove('zoomControl');
    map.controls.add(zoomInBtn);
    map.controls.add(zoomOutBtn);

    if (width < 768) {
      map.behaviors.disable('drag');
      map.behaviors.enable('multiTouch');
    }
  }

  clusterer.options.set({
    gridSize: 80,
    clusterDisableClickZoom: false
  });

  clusterer.add(markers);
  map.geoObjects.add(clusterer);

  /*
    На members.html карта лежит во вкладке «Интерактивная карта». Если при загрузке
    вкладка скрыта, карта создаётся с нулевым размером — при открытии вкладки
    пересчитываем размер и возвращаем карту в исходный центр.
  */
  const mapEl = document.getElementById('map');
  let createdHidden = mapEl.offsetParent === null;

  document.addEventListener('tabs:change', (event) => {
    if (event.detail.name !== 'map') {
      hideCard();
      return;
    }

    map.container.fitToViewport();
    if (createdHidden) {
      createdHidden = false;
      map.setCenter(window.__mapDefaultCenter, window.__mapDefaultZoom);
    }
  });
}